"""SageResearch-compatible academic search MCP server.

The server exposes the same two tool names used by SageResearch. arXiv is
queried directly; the Scholar tool uses SerpAPI Google Scholar when
``SERPAPI_KEY`` is configured, then Semantic Scholar and OpenAlex fallbacks.
OpenAlex is also exposed directly so workers can choose an open scholarly
index without first spending a request on another provider.
"""

from __future__ import annotations

import asyncio
import copy
from datetime import datetime, timezone
from email.utils import parsedate_to_datetime
import hashlib
import os
import re
import time
import xml.etree.ElementTree as ET
from typing import Any

import httpx
from mcp.server.fastmcp import FastMCP


mcp = FastMCP("deepresearch-paper-search")
ARXIV_API = os.getenv("DEEPRESEARCH_ARXIV_API_URL", "https://export.arxiv.org/api/query")
SEMANTIC_API = os.getenv(
    "DEEPRESEARCH_SEMANTIC_SCHOLAR_API_URL",
    "https://api.semanticscholar.org/graph/v1/paper/search",
)
OPENALEX_API = os.getenv(
    "DEEPRESEARCH_OPENALEX_API_URL",
    "https://api.openalex.org/works",
)

# One paper-search MCP process is shared by all Workers. Provider-scoped locks
# prevent parallel Workers from stampeding public academic APIs, while a short
# cache removes duplicate logical queries generated by neighboring tasks.
_PROVIDER_MIN_INTERVAL_SECONDS = {
    "arxiv": 0.5,
    "semantic_scholar": 1.0,
    "openalex": 0.5,
    "serpapi": 0.5,
}
_PROVIDER_LOCKS: dict[str, tuple[asyncio.AbstractEventLoop, asyncio.Lock]] = {}
_PROVIDER_NEXT_ALLOWED: dict[str, float] = {}
_QUERY_CACHE: dict[tuple[Any, ...], tuple[float, list[dict[str, Any]]]] = {}
_QUERY_CACHE_TTL_SECONDS = 300.0
_RATE_LIMIT_MAX_ATTEMPTS = 3


def _provider_lock(provider: str) -> asyncio.Lock:
    loop = asyncio.get_running_loop()
    current = _PROVIDER_LOCKS.get(provider)
    if current is None or current[0] is not loop:
        current = (loop, asyncio.Lock())
        _PROVIDER_LOCKS[provider] = current
    return current[1]


def _cache_get(key: tuple[Any, ...]) -> list[dict[str, Any]] | None:
    cached = _QUERY_CACHE.get(key)
    if cached is None:
        return None
    expires_at, rows = cached
    if expires_at <= time.monotonic():
        _QUERY_CACHE.pop(key, None)
        return None
    return copy.deepcopy(rows)


def _cache_put(key: tuple[Any, ...], rows: list[dict[str, Any]]) -> None:
    _QUERY_CACHE[key] = (
        time.monotonic() + _QUERY_CACHE_TTL_SECONDS,
        copy.deepcopy(rows),
    )


def _retry_after_seconds(response: httpx.Response, *, provider: str, attempt: int) -> float:
    raw = response.headers.get("Retry-After", "").strip()
    if raw:
        try:
            return max(0.0, min(float(raw), 60.0))
        except ValueError:
            try:
                parsed = parsedate_to_datetime(raw)
                if parsed.tzinfo is None:
                    parsed = parsed.replace(tzinfo=timezone.utc)
                return max(
                    0.0,
                    min((parsed - datetime.now(timezone.utc)).total_seconds(), 60.0),
                )
            except (TypeError, ValueError, OverflowError):
                pass
    # Stable jitter prevents synchronized retries without making evaluation
    # runs depend on process-global randomness.
    digest = hashlib.sha256(f"{provider}:{attempt}".encode("utf-8")).digest()
    jitter = int.from_bytes(digest[:2], "big") / 65535 * 0.25
    return min(30.0, 0.75 * (2**attempt) + jitter)


async def _provider_get(
    client: httpx.AsyncClient,
    provider: str,
    url: str,
    *,
    params: dict[str, Any],
) -> httpx.Response:
    """Serialize one provider and retry 429 using Retry-After-aware backoff."""

    async with _provider_lock(provider):
        wait_for = _PROVIDER_NEXT_ALLOWED.get(provider, 0.0) - time.monotonic()
        if wait_for > 0:
            await asyncio.sleep(wait_for)
        minimum_interval = _PROVIDER_MIN_INTERVAL_SECONDS.get(provider, 0.5)
        for attempt in range(_RATE_LIMIT_MAX_ATTEMPTS):
            response = await client.get(url, params=params)
            try:
                response.raise_for_status()
            except httpx.HTTPStatusError as exc:
                if exc.response.status_code != 429 or attempt + 1 >= _RATE_LIMIT_MAX_ATTEMPTS:
                    _PROVIDER_NEXT_ALLOWED[provider] = max(
                        _PROVIDER_NEXT_ALLOWED.get(provider, 0.0),
                        time.monotonic() + minimum_interval,
                    )
                    raise
                delay = max(
                    minimum_interval,
                    _retry_after_seconds(exc.response, provider=provider, attempt=attempt),
                )
                _PROVIDER_NEXT_ALLOWED[provider] = time.monotonic() + delay
                await asyncio.sleep(delay)
                continue
            _PROVIDER_NEXT_ALLOWED[provider] = time.monotonic() + minimum_interval
            return response
    raise RuntimeError(f"{provider} request exhausted retries")


def _reset_runtime_state_for_tests() -> None:
    """Reset process-level rate/cache state for isolated unit tests."""

    _PROVIDER_LOCKS.clear()
    _PROVIDER_NEXT_ALLOWED.clear()
    _QUERY_CACHE.clear()


def _limit(value: int) -> int:
    return max(1, min(int(value), 20))


def _openalex_abstract(inverted_index: Any) -> str:
    if not isinstance(inverted_index, dict):
        return ""
    positioned: list[tuple[int, str]] = []
    for word, positions in inverted_index.items():
        if not isinstance(positions, list):
            continue
        positioned.extend(
            (int(position), str(word))
            for position in positions
            if isinstance(position, int)
        )
    return " ".join(word for _, word in sorted(positioned))


def _openalex_params(**values: Any) -> dict[str, Any]:
    params = {key: value for key, value in values.items() if value not in (None, "")}
    email = os.getenv("OPENALEX_EMAIL")
    if email:
        params["mailto"] = email
    api_key = os.getenv("OPENALEX_API_KEY")
    if api_key:
        params["api_key"] = api_key
    return params


def _openalex_search_text(query: str) -> str:
    """OpenAlex rejects some punctuation in full-text search expressions."""

    return re.sub(r"[^\w\s-]+", " ", query, flags=re.UNICODE).strip()


def _openalex_result_url(item: dict[str, Any]) -> str:
    best_oa = item.get("best_oa_location") or {}
    primary = item.get("primary_location") or {}
    return str(
        best_oa.get("pdf_url")
        or primary.get("pdf_url")
        or item.get("doi")
        or best_oa.get("landing_page_url")
        or primary.get("landing_page_url")
        or item.get("id")
        or ""
    )


async def _search_openalex(
    query: str,
    limit: int,
    *,
    from_year: int | None = None,
    to_year: int | None = None,
    open_access_only: bool = False,
) -> list[dict[str, Any]]:
    cache_key = (
        "openalex",
        query.casefold(),
        limit,
        from_year,
        to_year,
        open_access_only,
    )
    cached = _cache_get(cache_key)
    if cached is not None:
        return cached
    filters: list[str] = []
    if from_year is not None:
        filters.append(f"from_publication_date:{int(from_year):04d}-01-01")
    if to_year is not None:
        filters.append(f"to_publication_date:{int(to_year):04d}-12-31")
    if open_access_only:
        filters.append("is_oa:true")
    params = _openalex_params(
        search=_openalex_search_text(query),
        **{"per-page": limit},
        filter=",".join(filters),
    )
    async with httpx.AsyncClient(timeout=20, trust_env=False) as client:
        response = await _provider_get(
            client,
            "openalex",
            OPENALEX_API,
            params=params,
        )
        payload = response.json()
    rows: list[dict[str, Any]] = []
    for item in payload.get("results", [])[:limit]:
        url = _openalex_result_url(item)
        if not url:
            continue
        best_oa = item.get("best_oa_location") or {}
        rows.append(
            {
                "title": str(item.get("display_name") or item.get("title") or ""),
                "url": str(url),
                "abstract": _openalex_abstract(item.get("abstract_inverted_index")),
                "authors": [
                    str((authorship.get("author") or {}).get("display_name") or "")
                    for authorship in (item.get("authorships") or [])
                    if (authorship.get("author") or {}).get("display_name")
                ],
                "published": item.get("publication_year"),
                "doi": str(item.get("doi") or ""),
                "openalex_id": str(item.get("id") or ""),
                "open_access_pdf": str(best_oa.get("pdf_url") or ""),
                "cited_by_count": item.get("cited_by_count"),
                "provider": "openalex",
            }
        )
    _cache_put(cache_key, rows)
    return rows


@mcp.tool(name="search_openalex", structured_output=True)
async def search_openalex(
    query: str,
    max_results: int = 5,
    from_year: int | None = None,
    to_year: int | None = None,
    open_access_only: bool = False,
) -> list[dict[str, Any]]:
    """Search OpenAlex for papers and prefer an available open-access PDF."""

    query = query.strip()
    if not query:
        return []
    if from_year is not None and to_year is not None and from_year > to_year:
        raise ValueError("from_year must be less than or equal to to_year")
    return await _search_openalex(
        query,
        _limit(max_results),
        from_year=from_year,
        to_year=to_year,
        open_access_only=open_access_only,
    )


@mcp.tool(name="search_arxiv", structured_output=True)
async def search_arxiv(query: str, max_results: int = 5) -> list[dict[str, Any]]:
    """Search arXiv and return title, abstract, authors, and paper URLs."""

    query = query.strip()
    if not query:
        return []
    limit = _limit(max_results)
    cache_key = ("arxiv", query.casefold(), limit)
    cached = _cache_get(cache_key)
    if cached is not None:
        return cached
    params = {
        "search_query": f"all:{query}",
        "start": 0,
        "max_results": limit,
        "sortBy": "relevance",
        "sortOrder": "descending",
    }
    async with httpx.AsyncClient(timeout=20, trust_env=False) as client:
        response = await _provider_get(client, "arxiv", ARXIV_API, params=params)
        xml = response.text
    root = ET.fromstring(xml)
    namespace = {"atom": "http://www.w3.org/2005/Atom"}
    rows: list[dict[str, Any]] = []
    for entry in root.findall("atom:entry", namespace):
        identifier = (entry.findtext("atom:id", default="", namespaces=namespace) or "").strip()
        title = " ".join(
            (entry.findtext("atom:title", default="", namespaces=namespace) or "").split()
        )
        abstract = " ".join(
            (entry.findtext("atom:summary", default="", namespaces=namespace) or "").split()
        )
        authors = [
            (author.findtext("atom:name", default="", namespaces=namespace) or "").strip()
            for author in entry.findall("atom:author", namespace)
        ]
        published = (entry.findtext("atom:published", default="", namespaces=namespace) or "").strip()
        if identifier:
            rows.append(
                {
                    "title": title,
                    "url": identifier,
                    "abstract": abstract,
                    "authors": authors,
                    "published": published,
                    "provider": "arxiv",
                }
            )
    _cache_put(cache_key, rows)
    return rows


async def _search_semantic_scholar(
    query: str, limit: int
) -> list[dict[str, Any]]:
    cache_key = ("semantic_scholar", query.casefold(), limit)
    cached = _cache_get(cache_key)
    if cached is not None:
        return cached
    params = {
        "query": query,
        "limit": limit,
        "fields": "title,abstract,year,url,authors,openAccessPdf",
    }
    async with httpx.AsyncClient(timeout=20, trust_env=False) as client:
        response = await _provider_get(
            client,
            "semantic_scholar",
            SEMANTIC_API,
            params=params,
        )
        payload = response.json()
    rows: list[dict[str, Any]] = []
    for item in payload.get("data", [])[:limit]:
        open_access = item.get("openAccessPdf") or {}
        url = open_access.get("url") or item.get("url") or ""
        if not url:
            continue
        rows.append(
            {
                "title": str(item.get("title") or ""),
                "url": url,
                "abstract": str(item.get("abstract") or ""),
                "authors": [
                    str(author.get("name") or "")
                    for author in (item.get("authors") or [])
                    if author.get("name")
                ],
                "published": item.get("year"),
                "provider": "semantic_scholar",
            }
        )
    _cache_put(cache_key, rows)
    return rows


@mcp.tool(name="search_google_scholar", structured_output=True)
async def search_google_scholar(query: str, max_results: int = 5) -> list[dict[str, Any]]:
    """Search scholarly papers with SerpAPI, Semantic Scholar, or OpenAlex."""

    query = query.strip()
    if not query:
        return []
    limit = _limit(max_results)
    serpapi_key = os.getenv("SERPAPI_KEY")
    if serpapi_key:
        cache_key = ("serpapi", query.casefold(), limit)
        cached = _cache_get(cache_key)
        if cached is not None:
            return cached
        params = {
            "engine": "google_scholar",
            "q": query,
            "num": limit,
            "api_key": serpapi_key,
        }
        async with httpx.AsyncClient(timeout=20, trust_env=False) as client:
            response = await _provider_get(
                client,
                "serpapi",
                "https://serpapi.com/search",
                params=params,
            )
            payload = response.json()
        rows = [
            {
                "title": str(item.get("title") or ""),
                "url": str(item.get("link") or item.get("publication_info", {}).get("summary") or ""),
                "abstract": str(item.get("snippet") or ""),
                "provider": "google_scholar",
            }
            for item in payload.get("organic_results", [])[:limit]
            if item.get("link")
        ]
        if rows:
            _cache_put(cache_key, rows)
            return rows
        return await _search_openalex(query, limit)

    try:
        rows = await _search_semantic_scholar(query, limit)
    except httpx.HTTPError:
        return await _search_openalex(query, limit)
    return rows or await _search_openalex(query, limit)


if __name__ == "__main__":
    mcp.run(transport="stdio")
